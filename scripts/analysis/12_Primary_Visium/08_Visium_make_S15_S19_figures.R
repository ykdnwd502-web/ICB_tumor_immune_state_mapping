safe_num <- function(x) {
  suppressWarnings(
    as.numeric(x)
  )
}

format_empirical_p <- function(p, n_perm = NA_integer_) {
  p <- safe_num(p)

  if (
    length(p) != 1L ||
    !is.finite(p)
  ) {
    return("P = NA")
  }

  if (
    is.finite(n_perm) &&
    n_perm > 0L &&
    abs(
      p -
      1 / (n_perm + 1)
    ) <
    1e-12
  ) {
    return(
      paste0(
        "empirical P = ",
        format(
          p,
          nsmall = 3
        ),
        " (",
        n_perm,
        " permutations)"
      )
    )
  }

  paste0(
    "P = ",
    format(
      p,
      digits = 3,
      scientific = TRUE
    )
  )
}

theme_visium <- function(base_size = 12.5, base_family = "sans") {
  ggplot2::theme_bw(base_size = base_size, base_family = base_family) +
  ggplot2::theme(
    plot.title = element_text(face = "bold", size = base_size + 2.5, hjust = 0.5, color = "black"),
    plot.subtitle = element_text(size = base_size - 1, hjust = 0.5, color = "black"),
    axis.title = element_text(face = "bold", size = base_size, color = "black"),
    axis.title.y = element_text(face = "bold", size = base_size - 1, color = "black"),
    axis.title.x = element_text(face = "bold", size = base_size, color = "black"),
    axis.text = element_text(size = base_size - 1.5, color = "black"),
    legend.title = element_text(face = "bold", size = base_size, color = "black"),
    legend.text = element_text(size = base_size - 1.5, color = "black"),
    strip.text = element_text(face = "bold", size = base_size - 0.5, color = "black"),
    panel.grid.major = element_line(color = "#E8E8E8", linewidth = 0.30),
    panel.grid.minor = element_blank(),
    panel.border = element_rect(color = "black", linewidth = 0.60),
    plot.background = element_rect(fill = "white", color = NA),
    panel.background = element_rect(fill = "white", color = NA)
  )
}

