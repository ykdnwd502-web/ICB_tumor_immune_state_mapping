## Reporting-only line wrapping for long manuscript-facing labels.
## Underlying analytical values/factors are NOT changed.
wrap_public_label <- function(x) {
  y <- as.character(x)

  ## Long derived dual-high category: use three semantic lines.
  y[y %in% c(
    "tumor-dedifferentiation/stromal-remodeling high only",
    "tumor-dedifferentiation/stromal-remodeling-high only",
    "Tumor-dedifferentiation/Stromal-remodeling high only",
    "Dediff/Stromal high only",
    "Dediff/Stromal-High Only"
  )] <- "tumor-dedifferentiation/\nstromal-remodeling\nhigh only"

  ## Long primary state: break at the biologically meaningful slash.
  y[y %in% c(
    "tumor-dedifferentiation/stromal-remodeling",
    "Tumor-dedifferentiation/Stromal-remodeling"
  )] <- "tumor-dedifferentiation/\nstromal-remodeling"

  ## Myeloid–Treg labels are wrapped only where panel width is constrained.
  y[y %in% c(
    "myeloid–Treg immunosuppressive",
    "myeloid-Treg immunosuppressive",
    "Myeloid–Treg Immunosuppressive",
    "Myeloid-Treg Immunosuppressive"
  )] <- "myeloid–Treg\nimmunosuppressive"

  y[y %in% c(
    "myeloid–Treg high only",
    "myeloid-Treg high only",
    "myeloid–Treg-high only",
    "myeloid-Treg-high only",
    "Myeloid–Treg high only",
    "Myeloid-Treg high only"
  )] <- "myeloid–Treg\nhigh only"

  y
}

## Compact manuscript-facing labels for dense four-category panels.
## DISPLAY ONLY: the underlying analytical Category values are unchanged.
compact_category_label <- function(x) {
  raw <- as.character(x)

  key <- raw
  key <- gsub("[\u2010\u2011\u2012\u2013\u2014\u2212]", "-", key, perl = TRUE)
  key <- tolower(trimws(key))
  key <- gsub("\\s+", " ", key, perl = TRUE)

  out <- raw

  out[key %in% c(
    "both high",
    "both-high",
    "dual-high",
    "dual high"
  )] <- "Both high"

  out[
    grepl("^myeloid-treg.*high only$", key) |
      key %in% c("myeloid-treg-high only")
  ] <- "Myeloid–Treg\nhigh only"

  out[key %in% c(
    "neither high",
    "neither-high"
  )] <- "Neither high"

  out[
    grepl("^tumor-dedifferentiation/stromal-remodeling.*high only$", key) |
      grepl("^tumor-dediff\\.?/stromal-remodeling.*high only$", key) |
      grepl("^dediff/stromal.*high only$", key)
  ] <- "Tumor-dediff./stromal-remodeling\nhigh only"

  out
}

