save_single_panel <- function(
  plot,
  figure,
  panel,
  width,
  height
) {
  base <- file.path(
    panel_figure_root,
    paste0(
      figure,
      "_",
      panel,
      ""
    )
  )

  ggplot2::ggsave(
    filename = paste0(
      base,
      ".pdf"
    ),
    plot = plot,
    width = width,
    height = height,
    units = "in",
    device = grDevices::cairo_pdf
  )

  ggplot2::ggsave(
    filename = paste0(
      base,
      ".jpg"
    ),
    plot = plot,
    width = width,
    height = height,
    units = "in",
    dpi = 300
  )
}

draw_plot_at <- function(
  plot,
  row,
  col,
  nrow,
  ncol
) {
  print(
    plot,
    vp = grid::viewport(
      layout.pos.row = row,
      layout.pos.col = col
    )
  )
}

save_grid_figure <- function(
  plots,
  positions,
  filename_stem,
  width,
  height,
  nrow,
  ncol,
  panel_labels = NULL,
  row_heights = rep(1, nrow),
  col_widths = rep(1, ncol)
) {
  if (length(row_heights) != nrow) {
    stop("row_heights must have length nrow.", call. = FALSE)
  }
  if (length(col_widths) != ncol) {
    stop("col_widths must have length ncol.", call. = FALSE)
  }

  render <- function() {
    grid::grid.newpage()
    grid::pushViewport(
      grid::viewport(
        layout = grid::grid.layout(
          nrow,
          ncol,
          heights = grid::unit(row_heights, "null"),
          widths = grid::unit(col_widths, "null")
        )
      )
    )

    for (
      i in seq_along(plots)
    ) {
      draw_plot_at(
        plots[[i]],
        positions[[i]][[1]],
        positions[[i]][[2]],
        nrow,
        ncol
      )
    }
  }

  pdf_file <- file.path(
    figure_root,
    paste0(
      filename_stem,
      ".pdf"
    )
  )

  jpg_file <- file.path(
    figure_root,
    paste0(
      filename_stem,
      ".jpg"
    )
  )

  grDevices::cairo_pdf(
    pdf_file,
    width = width,
    height = height
  )
  render()
  grDevices::dev.off()

  grDevices::jpeg(
    jpg_file,
    width = width,
    height = height,
    units = "in",
    res = 300,
    quality = 100
  )
  render()
  grDevices::dev.off()
}

assert_columns <- function(df, cols, label) {
  miss <- setdiff(
    cols,
    colnames(df)
  )

  if (length(miss) > 0L) {
    stop(
      label,
      " missing columns: ",
      paste(
        miss,
        collapse = ", "
      ),
      call. = FALSE
    )
  }
}


